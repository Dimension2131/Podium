const hiddenIds = () => {
    try {
        return new Set(JSON.parse(localStorage.getItem("podium_hidden") || "[]"));
    }
    catch (e) {
        return new Set();
    }
};

function visibleLib(lib) {
    const hid = hiddenIds();
    const sig = [...hid].join(",");
    if (view && viewSrc === lib && viewLen === lib.length && viewHid === sig) {
        return view;
    }
    view = lib.filter(l => !hid.has(l.id));
    viewSrc = lib;
    viewLen = lib.length;
    viewHid = sig;
    return view;
}

function hideList(id) {
    const hid = hiddenIds();
    hid.add(id);
    try {
        localStorage.setItem("podium_hidden", JSON.stringify([...hid].slice(-500)));
    }
    catch (e) {
        console.warn("Could not remember hidden lists:", e);
    }
    search();
}

const recent = () => {
    try {
        return JSON.parse(localStorage.getItem("podium_recent") || "[]");
    }
    catch (e) {
        return [];
    }
};

const saveRecent = l => localStorage.setItem("podium_recent", JSON.stringify(l.slice(0, 10)));

function remember(c) {
    const l = recent().filter(x => !(x.title === c.title && x.size === c.size));
    l.unshift({
        title: c.title,
        size: c.size,
        items: c.items,
        by: c.by
    });
    saveRecent(l);
}

function showRecent() {
    const l = recent();
    $("#recent").innerHTML = l.length ? `<label>Recently played</label><ul class="plist results">` + l.map((x, i) => `<li><span>${esc(x.title)} <small>top ${x.size}</small></span><span class="acts"><button class="alt" data-r="${i}">Use</button> <button class="alt" data-x="${i}" aria-label="Remove">×</button></span></li>`).join("") + "</ul>" : "";
}

$("#recent").onclick = e => {
    const b = e.target.closest("button");
    if (!b) {
        return;
    }
    const l = recent();
    if (b.dataset.r !== undefined) {
        setCustom(l[+b.dataset.r]);
    } else {
        l.splice(+b.dataset.x, 1);
        saveRecent(l);
        showRecent();
    }
};

function setCustom(c) {
    custom = c;
    $("#picked").hidden = !c;
    $("#finder").hidden = !!c;
    $("#create").disabled = !c;
    $("#pnote").hidden = !c || !String(c.by).startsWith("AI");
    if (c) {
        $("#pnote").textContent = c.by === "AI" ? "Generated by gemini from web search. Rankings can possibly be wrong, dont blame me." : "Generated by gemini from its own memory, without web search. Rankings can be outdated or wrong, dont blame me.";
        $("#pickedname").textContent = `${c.title} · top ${c.size} · by ${c.by}`;
        custVals = null;
        if (pmode === "custom") {
            pmode = "lin";
        }
        renderSetup();
    }
}

let tsel = "5";
let pmode = "lin";
let custVals = null;
const nOf = () => custom ? custom.size : 10;
const whole = (s, lo, hi) => /^\d+$/.test(String(s).trim()) && +s >= lo && +s <= hi;

function renderSetup() {
    for (const b of $("#tseg").children) {
        b.classList.toggle("on", b.dataset.t === tsel);
    }
    $("#tcwrap").hidden = tsel !== "c";
    for (const b of $("#pseg").children) {
        b.classList.toggle("on", b.dataset.p === pmode);
    }
    const cu = pmode === "custom";
    const n = nOf();
    $("#pcustom").hidden = !cu;
    if (cu) {
        if (!custVals || custVals.length !== n) {
            custVals = buildPoints("lin", n).map(String);
        }
        $("#pcustom").innerHTML = custVals.map((v, i) => `<label>#${i + 1}<input type="number" min="0" max="999" step="1" value="${esc(v)}" data-i="${i}"></label>`).join("");
        $("#ppreview").textContent = "Set the points for each rank (0 to 999).";
    } else {
        $("#ppreview").textContent = `Rank 1 to ${n}: ${buildPoints(pmode, n).join(", ")}`;
    }
}

