const gen = () => Array.from({ length: 4 }, () => "ABCDEFGHJKLMNPQRSTUVWXYZ"[Math.random() * 24 | 0]).join("");

async function add(c, n) {
    const res = await runTransaction(ref(db, `rooms/${c}/players`), p => {
        p = p || {};
        if (p[pid]) {
            return p;
        }
        if (Object.keys(p).length >= 10) {
            return;
        }
        p[pid] = {
            name: n,
            score: 0,
            hints: 0,
            active: true,
            online: true
        };
        return p;
    });
    return res.committed;
}

$("#create").onclick = async () => {
    if (!custom) {
        return toast("Pick a list first");
    }
    const n = name();
    if (!n) {
        return;
    }
    const cfg = readSetup();
    if (!cfg) {
        return;
    }
    const topic = custom.title;
    const size = custom.size;
    const items = custom.items.map(i => ({
        n: i.n,
        a: i.a || []
    }));
    for (let k = 0; k < 6; k++) {
        const c = gen();
        const r = await runTransaction(ref(db, "rooms/" + c), x => x ? undefined : {
            host: pid,
            status: "lobby",
            topic,
            size,
            items,
            ...cfg,
            created: Date.now()
        });
        if (r.committed) {
            remember(custom);
            await add(c, n);
            location.href = "lobby.html?room=" + c;
            return;
        }
    }
    toast("Could not create a room, try again");
};

const dest = r => (r.status === "lobby" ? "lobby" : r.status === "playing" ? "game" : "results") + ".html?room=";

async function watch(c, n) {
    const res = await runTransaction(ref(db, `rooms/${c}/spectators`), p => {
        p = p || {};
        if (p[pid]) {
            p[pid].name = n;
            p[pid].online = true;
            return p;
        }
        if (Object.keys(p).length >= 30) {
            return;
        }
        p[pid] = {
            name: n,
            online: true
        };
        return p;
    });
    return res.committed;
}

$("#join").onclick = async () => {
    const n = name();
    if (!n) {
        return;
    }
    const c = $("#joincode").value.trim().toUpperCase();
    if (c.length !== 4) {
        return toast("Room codes have 4 letters");
    }
    const r = (await get(ref(db, "rooms/" + c))).val();
    if (!r) {
        return toast("Room not found");
    }
    const mine = r.players && r.players[pid];
    if (r.status !== "lobby" && !mine) {
        return toast("That game already started");
    }
    if (!mine && !(await add(c, n))) {
        return toast("Room is full");
    }
    location.href = dest(r) + c;
};

$("#spectate").onclick = async () => {
    const n = name();
    if (!n) {
        return;
    }
    const c = $("#joincode").value.trim().toUpperCase();
    if (c.length !== 4) {
        return toast("Room codes have 4 letters");
    }
    const r = (await get(ref(db, "rooms/" + c))).val();
    if (!r) {
        return toast("Room not found");
    }
    if (!(r.players && r.players[pid]) && !(await watch(c, n))) {
        return toast("Too many spectators in that room");
    }
    location.href = dest(r) + c;
};